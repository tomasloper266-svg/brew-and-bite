/* Active language accessor (single source of truth lives in app.js state) */
const BB_LANG = {
  get() { return (window.BB_STATE && window.BB_STATE.lang) || 'ar'; }
};

/* Text helpers shared by views */
const BB_TEXT = {
  /** Strings for the active language (set by app.js). */
  current: BB_STRINGS.ar,
  /** Prefer the active language's field, falling back to the other. */
  pick(ar, en) {
    return (BB_LANG.get() === 'ar') ? (ar || en || '') : (en || ar || '');
  },
  /** Split a settings chip string ("قهوة · برجر | حلى") into trimmed chips. */
  splitList(s) {
    if (!s || !String(s).trim()) return [];
    return String(s).split(/[,،|;·•]+/).map(x => x.trim()).filter(Boolean);
  }
};
